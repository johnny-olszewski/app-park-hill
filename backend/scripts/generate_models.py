"""Generates one Swift and one Kotlin model per screen in /contract/generated
from the descriptions in /contract/screens. Run by `make models`; never edit
the output by hand.

Field names stay snake_case in the descriptions and become lower camel case
properties, mapped back to the JSON names. Any JSON (a property with no type)
is the app's `JSONValue` on iOS and `JsonElement` on Android. Both decoders
ignore unknown fields: Swift's `Decodable` does by default, and Android decodes
with `ContractJson` (`ignoreUnknownKeys`)."""

import sys

import names
import screens

MARKER = "GENERATED by `make models`"

SWIFT_TYPES = {"string": "String", "integer": "Int", "number": "Double", "boolean": "Bool", None: "JSONValue"}
KOTLIN_TYPES = {"string": "String", "integer": "Int", "number": "Double", "boolean": "Boolean", None: "JsonElement"}


def header(key: str) -> str:
    return f"// {MARKER} in /backend from contract/screens/{key}{screens.SUFFIX}. Do not edit.\n"


def field_type(field: dict, types: dict, array: str) -> str:
    if field.get("type") == "array":
        return array.format(field_type(field["items"], types, array))
    return types[field.get("type")]


def swift(key: str, schema: dict) -> str:
    title, properties = schema["title"], schema["properties"]
    out = header(key) + f"\n/// {schema['description']}\n"
    if not properties:
        return out + f"struct {title}: Decodable, Equatable {{}}\n"
    out += f"struct {title}: Decodable, Equatable {{\n"
    for name, field in properties.items():
        optional = "" if name in schema["required"] else "?"
        if "description" in field:
            out += f"    /// {field['description']}\n"
        out += f"    let {names.identifier(name)}: {field_type(field, SWIFT_TYPES, '[{}]')}{optional}\n"
    out += "\n    enum CodingKeys: String, CodingKey {\n"
    for name in properties:
        swift_name = names.identifier(name)
        out += f"        case {swift_name}\n" if swift_name == name else f'        case {swift_name} = "{name}"\n'
    return out + "    }\n}\n"


def kotlin(key: str, schema: dict) -> str:
    title, properties = schema["title"], schema["properties"]
    types = [field_type(f, KOTLIN_TYPES, "List<{}>") for f in properties.values()]
    imports = ["kotlinx.serialization.Serializable"]
    if any(names.identifier(n) != n for n in properties):
        imports.append("kotlinx.serialization.SerialName")
    if any("JsonElement" in t for t in types):
        imports.append("kotlinx.serialization.json.JsonElement")
    out = header(key) + "\npackage app.parkhill.contract\n\n"
    out += "".join(f"import {i}\n" for i in sorted(imports))
    out += f"\n/** {schema['description']} */\n@Serializable\n"
    if not properties:
        return out + f"class {title}\n"
    out += f"data class {title}(\n"
    for (name, field), kind in zip(properties.items(), types):
        if "description" in field:
            out += f"    /** {field['description']} */\n"
        kotlin_name = names.identifier(name)
        serial = "" if kotlin_name == name else f'@SerialName("{name}") '
        tail = "" if name in schema["required"] else "? = null"
        out += f"    {serial}val {kotlin_name}: {kind}{tail},\n"
    return out + ")\n"


def main() -> int:
    try:
        described = screens.load()
    except screens.ScreensError as error:
        print(f"contract/screens: {error}")
        return 1
    names.GENERATED_PATH.mkdir(exist_ok=True)
    for path in names.GENERATED_PATH.iterdir():
        if path.suffix in (".swift", ".kt") and MARKER in path.read_text().splitlines()[0]:
            path.unlink()
    for key, schema in described.items():
        (names.GENERATED_PATH / f"{schema['title']}.swift").write_text(swift(key, schema))
        (names.GENERATED_PATH / f"{schema['title']}.kt").write_text(kotlin(key, schema))
    print(f"Wrote {len(described)} Swift and Kotlin screen models in {names.GENERATED_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

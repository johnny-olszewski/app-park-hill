"""Generates the client constants in /contract/generated from
/contract/names.json. Run by `make names`; never edit the output by hand."""

import sys

import names

HEADER = "// GENERATED by `make names` in /backend from contract/names.json. Do not edit.\n"


def swift(data: dict) -> str:
    def cases(group: str) -> str:
        return "".join(f'    case {names.identifier(n)} = "{n}"\n' for n in data[group])

    keys = "".join(f'    static let {names.identifier(k)} = "{k}"\n' for k in data["screen_keys"])
    return (
        HEADER
        + "\n/// Backend RPC functions clients call.\n"
        + f"enum RPCFunction: String {{\n{cases('rpc_functions')}}}\n"
        + "\n/// Backend Edge Functions clients call.\n"
        + f"enum EdgeFunction: String {{\n{cases('edge_functions')}}}\n"
        + "\n/// Screen keys the backend returns. Strings, because screen keys arrive in payloads.\n"
        + f"enum ScreenKey {{\n{keys}}}\n"
    )


def kotlin(data: dict) -> str:
    def entries(group: str) -> str:
        return ",\n".join(f'    {names.identifier(n)}("{n}")' for n in data[group]) + ",\n"

    keys = "".join(f'    const val {names.identifier(k)} = "{k}"\n' for k in data["screen_keys"])
    return (
        HEADER
        + "\npackage app.parkhill.contract\n"
        + "\n/** Backend RPC functions clients call. */\n"
        + f"enum class RpcFunction(val value: String) {{\n{entries('rpc_functions')}}}\n"
        + "\n/** Backend Edge Functions clients call. */\n"
        + f"enum class EdgeFunction(val value: String) {{\n{entries('edge_functions')}}}\n"
        + "\n/** Screen keys the backend returns. Strings, because screen keys arrive in payloads. */\n"
        + f"object ScreenKey {{\n{keys}}}\n"
    )


def main() -> int:
    try:
        data = names.load()
    except names.NamesError as error:
        print(f"names.json: {error}")
        return 1
    names.GENERATED_PATH.mkdir(exist_ok=True)
    (names.GENERATED_PATH / "ContractNames.swift").write_text(swift(data))
    (names.GENERATED_PATH / "ContractNames.kt").write_text(kotlin(data))
    print(f"Wrote ContractNames.swift and ContractNames.kt in {names.GENERATED_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

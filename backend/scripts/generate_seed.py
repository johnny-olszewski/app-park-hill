"""Generates backend/supabase/seed.sql from /contract/seed/dataset.json.
Run with `make seed`. Never edit seed.sql by hand."""

import json

import dataset


def sql_string(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def persona_sql(persona: dict, password: str) -> str:
    uid = dataset.persona_uuid(persona["id"])
    email = sql_string(persona["email"])
    metadata = sql_string(json.dumps({"display_name": persona["display_name"]}))
    identity = sql_string(json.dumps({"sub": uid, "email": persona["email"], "email_verified": True}))
    banned_until = "'2999-12-31 00:00:00+00'" if persona["state"] == "banned" else "null"
    return f"""-- {persona['id']}: {persona['description']}
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, banned_until, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values (
  '00000000-0000-0000-0000-000000000000', '{uid}', 'authenticated', 'authenticated',
  {email}, extensions.crypt({sql_string(password)}, extensions.gen_salt('bf')), now(),
  '{{"provider": "email", "providers": ["email"]}}', {metadata}, {banned_until}, now(), now(),
  '', '', '', ''
);
insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values ('{uid}', '{uid}', {identity}, 'email', now(), now(), now());
""" + roles_sql(uid, persona.get("roles", []))


def roles_sql(uid: str, roles: list[str]) -> str:
    """Assigned roles beyond the sign-up role, which every account gets."""
    if not roles:
        return ""
    keys = ", ".join(sql_string(r) for r in roles)
    return f"""insert into public.user_roles (user_id, role_id)
select '{uid}', r.id from public.roles r where r.key in ({keys});
"""


def person_sql(person: dict) -> str:
    """An account that cannot sign in: no password and no identity."""
    uid = dataset.persona_uuid(person["id"])
    metadata = sql_string(json.dumps({"display_name": person["display_name"]}))
    return f"""insert into auth.users (instance_id, id, aud, role, email, encrypted_password, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', '{uid}', 'authenticated', 'authenticated', {sql_string(dataset.person_email(person['id']))}, '', '{{}}', {metadata}, now(), now(), '', '', '', '');
"""


def optional_sql(value) -> str:
    return "null" if value is None else sql_string(str(value))


def group_sql(group: dict) -> str:
    gid = dataset.group_uuid(group["id"])
    lines = [f"""-- {group['id']}
insert into public.groups (id, group_type_id, name, description, meeting_day, meeting_time, location, archived_at)
select '{gid}', t.id, {sql_string(group['name'])}, {sql_string(group.get('description', ''))},
  {group.get('meeting_day') if group.get('meeting_day') is not None else 'null'}, {optional_sql(group.get('meeting_time'))}, {sql_string(group.get('location', ''))},
  {"now()" if group.get('archived') else 'null'}
from public.group_types t where t.key = {sql_string(group['type'])};
"""]
    for table, people in (("group_members", group.get("members", [])), ("group_leaders", group.get("leaders", []))):
        for person in people:
            lines.append(f"insert into public.{table} (group_id, user_id) values ('{gid}', '{dataset.persona_uuid(person)}');\n")
    return "".join(lines)


def generate(data: dict) -> str:
    header = """-- GENERATED by `make seed` from contract/seed/dataset.json. Do not edit.
-- Test data only: local persona accounts sharing the local password, their
-- assigned roles, people who cannot sign in, and test groups. Never
-- applied to a hosted project. App configuration belongs in migrations.

"""
    personas = "\n".join(persona_sql(p, data["local_password"]) for p in data["personas"])
    people = "".join(person_sql(p) for p in data.get("people", []))
    groups = "\n".join(group_sql(g) for g in data.get("groups", []))
    return (
        header
        + personas
        + ("\n-- People who cannot sign in\n\n" + people if people else "")
        + ("\n-- Groups\n\n" + groups if groups else "")
    )


def main() -> None:
    dataset.SEED_PATH.write_text(generate(dataset.load()))
    print(f"Wrote {dataset.SEED_PATH.relative_to(dataset.REPO)}")


if __name__ == "__main__":
    main()

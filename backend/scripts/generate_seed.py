"""Generates backend/supabase/seed.sql from /contract/seed/dataset.json.
Run with `make seed`. Never edit seed.sql by hand."""

import json

import dataset


def sql_string(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def persona_sql(persona: dict, password: str) -> str:
    uid = dataset.persona_uuid(persona["id"])
    email = sql_string(persona["email"])
    metadata = sql_string(json.dumps({"display_name": persona["display_name"]}))
    identity = sql_string(json.dumps({"sub": uid, "email": persona["email"], "email_verified": True}))
    banned_until = "'2999-12-31 00:00:00+00'" if persona["state"] == "banned" else "null"
    return f"""-- {persona['id']}: {persona['description']}
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, banned_until, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values (
  '00000000-0000-0000-0000-000000000000', '{uid}', 'authenticated', 'authenticated',
  {email}, extensions.crypt({sql_string(password)}, extensions.gen_salt('bf')), now(),
  '{{"provider": "email", "providers": ["email"]}}', {metadata}, {banned_until}, now(), now(),
  '', '', '', ''
);
insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values ('{uid}', '{uid}', {identity}, 'email', now(), now(), now());
"""


def generate(data: dict) -> str:
    header = """-- GENERATED by `make seed` from contract/seed/dataset.json. Do not edit.
-- Test data only: local persona accounts sharing the local password. Never
-- applied to a hosted project. App configuration belongs in migrations.

"""
    return header + "\n".join(persona_sql(p, data["local_password"]) for p in data["personas"])


def main() -> None:
    dataset.SEED_PATH.write_text(generate(dataset.load()))
    print(f"Wrote {dataset.SEED_PATH.relative_to(dataset.REPO)}")


if __name__ == "__main__":
    main()

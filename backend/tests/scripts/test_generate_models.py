"""Unit tests for scripts/generate_models.py: how description fields become
Swift and Kotlin types. No Supabase stack needed."""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))

import generate_models  # noqa: E402

SCHEMA = {
    "title": "ExampleData",
    "description": "Example.",
    "properties": {
        "item": {"$ref": "../types/Item.schema.json"},
        "items": {"type": "array", "items": {"$ref": "../types/Item.schema.json"}},
        "data": {"type": "object"},
        "anything": {},
    },
    "required": ["item", "items", "data", "anything"],
}


class FieldTypes(unittest.TestCase):
    def test_a_ref_is_the_referenced_type(self):
        swift = generate_models.swift("screens/example.schema.json", SCHEMA)
        self.assertIn("let item: Item\n", swift)
        self.assertIn("let items: [Item]\n", swift)
        kotlin = generate_models.kotlin("screens/example.schema.json", SCHEMA)
        self.assertIn("val item: Item,\n", kotlin)
        self.assertIn("val items: List<Item>,\n", kotlin)

    def test_any_object_and_any_json(self):
        swift = generate_models.swift("screens/example.schema.json", SCHEMA)
        self.assertIn("let data: JSONValue\n", swift)
        self.assertIn("let anything: JSONValue\n", swift)
        kotlin = generate_models.kotlin("screens/example.schema.json", SCHEMA)
        self.assertIn("val data: JsonObject,\n", kotlin)
        self.assertIn("val anything: JsonElement,\n", kotlin)
        self.assertIn("import kotlinx.serialization.json.JsonObject\n", kotlin)
        self.assertIn("import kotlinx.serialization.json.JsonElement\n", kotlin)

    def test_an_enum_is_its_own_type_named_after_the_type_and_field(self):
        schema = {**SCHEMA, "properties": {"presentation": {"type": "string", "enum": ["push", "full_screen_cover"]}}, "required": ["presentation"]}
        swift = generate_models.swift("types/Example.schema.json", schema)
        self.assertIn("let presentation: ExampleDataPresentation\n", swift)
        self.assertIn("enum ExampleDataPresentation: String, Codable, Equatable, Sendable {\n", swift)
        self.assertIn('    case fullScreenCover = "full_screen_cover"\n', swift)
        kotlin = generate_models.kotlin("types/Example.schema.json", schema)
        self.assertIn("val presentation: ExampleDataPresentation,\n", kotlin)
        self.assertIn('    @SerialName("full_screen_cover") FULL_SCREEN_COVER,\n', kotlin)

    def test_a_union_decodes_on_type_and_keeps_unknown_types(self):
        member = {
            "title": "Go", "description": "Go.",
            "properties": {"type": {"type": "string", "enum": ["go"]}}, "required": ["type"],
        }
        union = {"title": "Act", "description": "Act.", "oneOf": [{"$ref": "Go.schema.json"}]}
        types = {"Go": member, "Act": union}
        swift = generate_models.swift("types/Act.schema.json", union, types)
        self.assertIn("enum Act: Codable, Equatable, Sendable {\n    case go(Go)\n", swift)
        self.assertIn("case unknown(type: String?)", swift)
        self.assertIn('case "go": self = .go(try Go(from: decoder))', swift)
        kotlin = generate_models.kotlin("types/Act.schema.json", union, {}, types)
        self.assertIn("sealed interface Act {", kotlin)
        self.assertIn('"go" -> input.json.decodeFromJsonElement(Go.serializer(), element)', kotlin)
        self.assertIn("else -> Act.Unknown(type)", kotlin)
        self.assertTrue(generate_models.kotlin("types/Go.schema.json", member, {"Go": ["Act"]}).count(") : Act\n"))

    def test_the_header_names_the_source(self):
        swift = generate_models.swift("types/Item.schema.json", SCHEMA)
        self.assertTrue(swift.startswith("// GENERATED by `make models` in /backend from contract/types/Item.schema.json."))


if __name__ == "__main__":
    unittest.main()

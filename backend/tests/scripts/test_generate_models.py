"""Unit tests for scripts/generate_models.py: how description fields become
Swift and Kotlin types. No Supabase stack needed."""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))

import generate_models  # noqa: E402

SCHEMA = {
    "title": "ExampleData",
    "description": "Example.",
    "properties": {
        "item": {"$ref": "../types/Item.schema.json"},
        "items": {"type": "array", "items": {"$ref": "../types/Item.schema.json"}},
        "data": {"type": "object"},
        "anything": {},
    },
    "required": ["item", "items", "data", "anything"],
}


class FieldTypes(unittest.TestCase):
    def test_a_ref_is_the_referenced_type(self):
        swift = generate_models.swift("screens/example.schema.json", SCHEMA)
        self.assertIn("let item: Item\n", swift)
        self.assertIn("let items: [Item]\n", swift)
        kotlin = generate_models.kotlin("screens/example.schema.json", SCHEMA)
        self.assertIn("val item: Item,\n", kotlin)
        self.assertIn("val items: List<Item>,\n", kotlin)

    def test_any_object_and_any_json(self):
        swift = generate_models.swift("screens/example.schema.json", SCHEMA)
        self.assertIn("let data: JSONValue\n", swift)
        self.assertIn("let anything: JSONValue\n", swift)
        kotlin = generate_models.kotlin("screens/example.schema.json", SCHEMA)
        self.assertIn("val data: JsonObject,\n", kotlin)
        self.assertIn("val anything: JsonElement,\n", kotlin)
        self.assertIn("import kotlinx.serialization.json.JsonObject\n", kotlin)
        self.assertIn("import kotlinx.serialization.json.JsonElement\n", kotlin)

    def test_the_header_names_the_source(self):
        swift = generate_models.swift("types/Item.schema.json", SCHEMA)
        self.assertTrue(swift.startswith("// GENERATED by `make models` in /backend from contract/types/Item.schema.json."))


if __name__ == "__main__":
    unittest.main()
